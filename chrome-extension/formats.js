/*
 * fxproxy Token Extractor — export formatters.
 * Pure functions, no Chrome APIs, so the same file runs in the popup and in
 * a plain Node process for tests. Every output here is accepted by
 * fxproxy/cookieutil.py (the panel's "Cookie / 插件导出" mode).
 */
(function (root, factory) {
  var api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.FxproxyFormats = api;
})(typeof window !== "undefined" ? window : globalThis, function () {
  "use strict";

  // Prefer the de-duplicated token list; fall back to per-account tokens.
  function tokensOf(payload) {
    var out = [];
    var seen = {};
    var list = (payload && payload.session_tokens) || [];
    for (var i = 0; i < list.length; i++) {
      if (list[i] && !seen[list[i]]) { seen[list[i]] = 1; out.push(list[i]); }
    }
    var accts = (payload && payload.accounts) || [];
    for (var j = 0; j < accts.length; j++) {
      var st = accts[j].session_token || accts[j].sessionToken;
      if (st && !seen[st]) { seen[st] = 1; out.push(st); }
    }
    return out;
  }

  function toJSON(payload) {
    // Keep the accounts array (email/uid) — it's the richest form.
    var clean = {
      version: 1,
      source: payload.source || "fxproxy-chrome-extension",
      origin: payload.origin || "",
      extracted_at: payload.extracted_at || "",
      accounts: payload.accounts || [],
      session_tokens: tokensOf(payload)
    };
    return JSON.stringify(clean, null, 2);
  }

  function toLines(payload) {
    return tokensOf(payload).join("\n") + "\n";
  }

  function toCsv(payload) {
    return tokensOf(payload).join(", ") + "\n";
  }

  function toCookieHeader(payload) {
    // cookieutil parses `name=value; ...` and classifies by name ("session").
    return tokensOf(payload).map(function (t) {
      return "sessionToken=" + t;
    }).join("; ") + "\n";
  }

  function toNetscape(payload) {
    var lines = [
      "# Netscape HTTP Cookie File",
      "# Generated by fxproxy-chrome-extension",
      ""
    ];
    var host = "accounts.firefox.com";
    try {
      if (payload.origin) host = payload.origin.replace(/^https?:\/\//, "").split("/")[0] || host;
    } catch (e) { /* keep default */ }
    // cookieutil ignores expiry; a far-future epoch keeps the file valid.
    var expiry = "4102444800";
    tokensOf(payload).forEach(function (t) {
      lines.push([
        host, "TRUE", "/", "TRUE", expiry, "sessionToken", t
      ].join("\t"));
    });
    return lines.join("\n") + "\n";
  }

  // Accounts with email, one per line — handy for eyeballing which token is
  // which account. cookieutil reads only the token, so this is still importable.
  function toAccountLines(payload) {
    var accts = payload.accounts || [];
    if (!accts.length) return toLines(payload);
    return accts.map(function (a) {
      var label = a.email || a.uid || "account";
      return (label + " " + (a.session_token || a.sessionToken || "")).trim();
    }).join("\n") + "\n";
  }

  var FORMATS = {
    json:     { label: "JSON（含邮箱/uid，推荐）", ext: "json", fn: toJSON },
    lines:    { label: "每行一个 sessionToken", ext: "txt", fn: toLines },
    cookie:   { label: "Cookie 头（sessionToken=…）", ext: "txt", fn: toCookieHeader },
    netscape: { label: "Netscape cookies.txt", ext: "txt", fn: toNetscape },
    csv:      { label: "逗号分隔（脚本/环境变量）", ext: "txt", fn: toCsv },
    accounts: { label: "账号+邮箱（人工核对）", ext: "txt", fn: toAccountLines }
  };

  function format(payload, kind) {
    var f = FORMATS[kind] || FORMATS.json;
    return f.fn(payload);
  }

  return {
    FORMATS: FORMATS,
    tokensOf: tokensOf,
    format: format,
    toJSON: toJSON,
    toLines: toLines,
    toCookieHeader: toCookieHeader,
    toNetscape: toNetscape,
    toCsv: toCsv,
    toAccountLines: toAccountLines
  };
});
